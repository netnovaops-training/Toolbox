"""build_index.py - rebuild LOGBOOK.md and JACKET.md from logbook entry frontmatter.

Reads every entry in knowledge/{troubleshooting,installs,projects,learning}/ (files
starting with "_" and README/GUIDELINE are skipped), then writes:
  LOGBOOK.md  counts, timeline, open/solved, and views by type, language and branch
  JACKET.md   every finished lesson, grouped by technology, linked to its entry + branch

Usage (from the repo root):
  python -I code/local/build_index.py           write the two files
  python -I code/local/build_index.py --check   validate entries only (used on PRs)

No third-party packages. Output is deterministic: same entries -> same bytes.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPO = "netnovaops-training/Toolbox"
FOLDERS = {  # folder -> type it must contain
    "troubleshooting": "troubleshooting",
    "installs": "install",
    "projects": "project",
    "learning": "learning",
}
TYPE_ORDER = ["project", "install", "troubleshooting", "learning"]
TYPE_LABEL = {"project": "Projects", "install": "Installs",
              "troubleshooting": "Troubleshooting", "learning": "Learning"}
TYPE_COUNT = {"project": ("project", "projects"), "install": ("install", "installs"),
              "troubleshooting": ("troubleshooting", "troubleshooting"),
              "learning": ("learning note", "learning notes")}
# programming languages the "By language" view recognises in the tech list by itself;
# anything else can be named in an entry's optional `lang:` line, e.g. lang: [zig]
LANGUAGES = {
    "bash", "shell", "sh", "zsh", "powershell", "python", "rust", "go", "golang",
    "javascript", "js", "typescript", "ts", "node", "nodejs", "java", "kotlin", "swift",
    "c", "cpp", "c++", "csharp", "c#", "dotnet", "ruby", "php", "perl", "lua", "r",
    "sql", "html", "css", "dart", "scala", "haskell", "elixir", "awk", "sed",
}
STATUSES = ["open", "in-progress", "blocked", "resolved"]
OPEN = {"open", "in-progress", "blocked"}
REQUIRED = ["type", "title", "date", "branch", "tech", "status"]
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
GENERATED = "<!-- GENERATED by code/local/build_index.py - do not edit by hand. -->"


def parse_frontmatter(text):
    """Return (fields, error). Fields are str or list[str]; error is None if fine."""
    if text.startswith("\ufeff"):
        return None, "file starts with a BOM; save it as UTF-8 without BOM"
    text = text.replace("\r\n", "\n")
    if not text.startswith("---\n"):
        return None, "no frontmatter (first line must be ---)"
    end = text.find("\n---\n", 3)
    if end == -1:
        return None, "frontmatter is never closed with ---"
    fields = {}
    for n, line in enumerate(text[4:end].split("\n"), start=2):
        if not line.strip():
            continue
        if ":" not in line:
            return None, f"line {n}: expected 'key: value', got {line!r}"
        key, _, value = line.partition(":")
        key, value = key.strip(), value.strip()
        if value.startswith("[") and value.endswith("]"):
            fields[key] = [v.strip().strip("'\"") for v in value[1:-1].split(",") if v.strip()]
        else:
            fields[key] = value.strip("'\"")
    return fields, None


def is_placeholder(value):
    return not value or "XXX" in value or value.startswith("__")


def load_entries():
    entries, errors = [], []
    for folder, want_type in FOLDERS.items():
        base = ROOT / "knowledge" / folder
        if not base.is_dir():
            continue
        for path in sorted(base.glob("*.md")):
            if path.name.startswith("_") or path.name in ("README.md", "GUIDELINE.md"):
                continue
            rel = path.relative_to(ROOT).as_posix()
            fields, err = parse_frontmatter(path.read_text(encoding="utf-8"))
            if err:
                errors.append(f"{rel}: {err}")
                continue
            problems = [f"missing '{k}'" for k in REQUIRED
                        if k not in fields or (k != "tech" and is_placeholder(fields[k]))]
            if fields.get("type") and fields["type"] != want_type:
                problems.append(f"type is '{fields['type']}' but the folder holds '{want_type}'")
            if fields.get("status") and fields["status"] not in STATUSES:
                problems.append(f"status '{fields['status']}' is not one of {', '.join(STATUSES)}")
            for k in ("date", "opened", "closed"):
                v = fields.get(k)
                if isinstance(v, str) and v and not DATE_RE.match(v):
                    problems.append(f"{k} '{v}' is not YYYY-MM-DD")
            if not isinstance(fields.get("tech", []), list):
                problems.append("tech must be a list, e.g. [docker, linux]")
            if "lang" in fields and fields["lang"] != "" and not isinstance(fields["lang"], list):
                problems.append("lang must be a list, e.g. [zig]")
            if fields.get("status") == "resolved":
                for k in ("summary", "lesson"):
                    if is_placeholder(fields.get(k, "")):
                        problems.append(f"resolved entries need a real '{k}'")
            if problems:
                errors.append(f"{rel}: " + "; ".join(problems))
                continue
            fields["path"] = rel
            if isinstance(fields.get("tags"), str):
                fields["tags"] = [fields["tags"]] if fields["tags"] else []
            entries.append(fields)
    # newest date first; within one date, titles A->Z (two stable sorts)
    entries.sort(key=lambda e: e["title"].lower())
    entries.sort(key=lambda e: e["date"], reverse=True)
    return entries, errors


# ---------- rendering helpers ----------

def plural(n, one, many=None):
    return f"{n} {one if n == 1 else (many or one + 's')}"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def branch_url(branch):
    return f"https://github.com/{REPO}/tree/{branch}"


def entry_link(e, prefix=""):
    return f"[{cell(e['title'])}]({prefix}{e['path']})"


def tech_text(e):
    return ", ".join(e["tech"]) if e["tech"] else "-"


def table(rows, cols):
    """rows: list of entries; cols: list of (header, func(entry) -> str)."""
    if not rows:
        return "_None yet._\n"
    out = ["| " + " | ".join(h for h, _ in cols) + " |",
           "|" + "|".join("---" for _ in cols) + "|"]
    for e in rows:
        out.append("| " + " | ".join(f(e) for _, f in cols) + " |")
    return "\n".join(out) + "\n"


COL_DATE = ("Date", lambda e: e["date"])
TYPE_NAME = {"project": "Project", "install": "Install",
             "troubleshooting": "Troubleshooting", "learning": "Learning"}
COL_TYPE = ("Type", lambda e: TYPE_NAME[e["type"]])
COL_TITLE = ("Title", entry_link)
COL_TECH = ("Tech", tech_text)
COL_STATUS = ("Status", lambda e: e["status"])
COL_BRANCH = ("Branch", lambda e: f"[`{cell(e['branch'])}`]({branch_url(e['branch'])})")
COL_CLOSED = ("Closed", lambda e: e.get("closed") or "-")
COL_SUMMARY = ("Summary", lambda e: "-" if is_placeholder(e.get("summary", ""))
               else cell(e["summary"]))


def details(summary, body):
    return f"<details>\n<summary>{summary}</summary>\n\n{body}\n</details>\n"


def langs(e):
    """Programming languages for an entry: known ones in tech, plus its lang: list."""
    extra = e.get("lang") if isinstance(e.get("lang"), list) else []
    return sorted({t for t in e["tech"] if t in LANGUAGES} | set(extra))


def build_logbook(entries):
    by_type = {t: [e for e in entries if e["type"] == t] for t in TYPE_ORDER}
    open_rows = [e for e in entries if e["status"] in OPEN]
    done_rows = [e for e in entries if e["status"] == "resolved"]
    techs = sorted({t for e in entries for t in e["tech"]}) + (
        ["untagged"] if any(not e["tech"] for e in entries) else [])
    languages = sorted({lang for e in entries for lang in langs(e)})
    branches = sorted({e["branch"] for e in entries})

    counts = " · ".join(plural(len(by_type[t]), *TYPE_COUNT[t]) for t in TYPE_ORDER)
    out = [
        "# Logbook",
        "",
        GENERATED,
        "",
        "Every troubleshooting fix, install, project and learning note I've written up,",
        "sorted automatically. Each title opens the full write-up.",
        "",
        f"**{plural(len(entries), 'entry', 'entries')}** - {counts}  ",
        f"**{len(open_rows)} open** · **{len(done_rows)} resolved**",
        "",
        "Tickets still being worked on (on their own branches) are listed in "
        "[OPEN.md](OPEN.md).",
        "",
        "Jump to: [Timeline](#timeline) · [Open](#open--ongoing) · "
        "[Resolved](#resolved--completed) · [By type](#by-type) · "
        "[By topic](#by-topic) · [By language](#by-language) · [By branch](#by-branch) · "
        "[Open tickets](OPEN.md) · [Career jacket](JACKET.md)",
        "",
        "## Timeline",
        "",
        "Newest first.",
        "",
        table(entries, [COL_DATE, COL_TYPE, COL_TITLE, COL_TECH, COL_STATUS]),
        "## Open / ongoing",
        "",
        table(open_rows, [COL_DATE, COL_TYPE, COL_TITLE, COL_STATUS, COL_BRANCH]),
        "## Resolved / completed",
        "",
        table(done_rows, [COL_CLOSED, COL_TYPE, COL_TITLE, COL_SUMMARY]),
        "## By type",
        "",
    ]
    for t in TYPE_ORDER:
        out += [f"### {TYPE_LABEL[t]} ({len(by_type[t])})", "",
                table(by_type[t], [COL_DATE, COL_TITLE, COL_TECH, COL_STATUS])]
    out += ["## By topic", "",
            "Every tag - tools, tech and subjects. Click one to see only its entries.", ""]
    for tech in techs:
        rows = [e for e in entries if (tech in e["tech"]) or (tech == "untagged" and not e["tech"])]
        out.append(details(f"<b>{tech}</b> ({len(rows)})",
                           table(rows, [COL_DATE, COL_TYPE, COL_TITLE, COL_STATUS])))
    if not techs:
        out.append("_None yet._\n")
    out += ["## By language", "",
            "Only the programming languages, so code work is easy to find.", ""]
    for lang in languages:
        rows = [e for e in entries if lang in langs(e)]
        out.append(details(f"<b>{lang}</b> ({len(rows)})",
                           table(rows, [COL_DATE, COL_TYPE, COL_TITLE, COL_STATUS])))
    if not languages:
        out.append("_No code entries yet. Tag one with a language (python, rust, bash...) "
                   "and it appears here._\n")
    out += ["## By branch", "",
            "The git branch each piece of work was done on.", ""]
    for b in branches:
        rows = [e for e in entries if e["branch"] == b]
        out.append(details(f"<code>{b}</code> ({len(rows)})",
                           f"[Open this branch on GitHub]({branch_url(b)})\n\n"
                           + table(rows, [COL_DATE, COL_TYPE, COL_TITLE, COL_STATUS])))
    if not branches:
        out.append("_None yet._\n")
    return "\n".join(out).rstrip() + "\n"


def build_jacket(entries):
    lessons = [e for e in entries if not is_placeholder(e.get("lesson", ""))]
    techs = sorted({t for e in lessons for t in e["tech"]}) + (
        ["general"] if any(not e["tech"] for e in lessons) else [])
    out = [
        "# Career jacket",
        "",
        GENERATED,
        "",
        "Lessons from real work, rolled up automatically from the [logbook](LOGBOOK.md).",
        "Each one links to the full write-up and to the branch where the work happened.",
        "",
        f"**{plural(len(lessons), 'lesson')}** across "
        f"**{plural(len([t for t in techs if t != 'general']), 'technology', 'technologies')}**.",
        "",
    ]
    if not lessons:
        out.append("_No lessons yet - they appear here as entries get a real `lesson:`._")
    for tech in techs:
        rows = [e for e in lessons if (tech in e["tech"]) or (tech == "general" and not e["tech"])]
        out += [f"## {tech}", ""]
        for e in rows:
            status = "" if e["status"] == "resolved" else f" _({e['status']})_"
            out.append(
                f"- **{cell(e['title'])}** ({e['date']}){status} - {cell(e['lesson'])}  \n"
                f"  [Write-up]({e['path']}) · "
                f"[Branch `{cell(e['branch'])}`]({branch_url(e['branch'])})")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


SHOWCASE_LIMIT = 5
BEGIN, END = "<!-- BEGIN LATEST WORK -->", "<!-- END LATEST WORK -->"


def showcased(e):
    """Resolved projects show automatically; anything else opts in with showcase: true."""
    flagged = str(e.get("showcase", "")).lower() in ("true", "yes")
    finished = e["status"] == "resolved" and not is_placeholder(e.get("summary", ""))
    return finished and (e["type"] == "project" or flagged)


def build_latest(entries):
    rows = [e for e in entries if showcased(e)][:SHOWCASE_LIMIT]
    if not rows:
        return "_Finished projects appear here automatically._\n"
    out = []
    for e in rows:
        tech = " ".join(f"`{t}`" for t in e["tech"])
        line = (f"- **[{cell(e['title']).capitalize()}]({e['path']})** "
                f"({e.get('closed') or e['date']}) - {cell(e['summary'])}")
        out.append(f"{line}  \n  {tech}" if tech else line)
    out.append("\n[Everything in the logbook](LOGBOOK.md)")
    return "\n".join(out) + "\n"


def write_section(path, body):
    """Replace only the text between the LATEST WORK markers in a hand-written page."""
    if not path.exists():
        return
    old = path.read_text(encoding="utf-8")
    if BEGIN not in old or END not in old:
        return
    head, rest = old.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    write(path, f"{head}{BEGIN}\n{body}{END}{tail}")


def write(path, content):
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old == content:
        print(f"unchanged: {path.name}")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"wrote: {path.name}")


def main():
    check_only = "--check" in sys.argv[1:]
    entries, errors = load_entries()
    if errors:
        print("Logbook entries with problems:")
        for err in errors:
            print(f"  - {err}")
        print("Fix the frontmatter at the top of those files (see the _template.md in the folder).")
        return 1
    print(f"{plural(len(entries), 'entry', 'entries')} OK")
    if check_only:
        return 0
    write(ROOT / "LOGBOOK.md", build_logbook(entries))
    write(ROOT / "JACKET.md", build_jacket(entries))
    write_section(ROOT / "PORTFOLIO.md", build_latest(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main())
