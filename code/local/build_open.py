"""build_open.py - rebuild OPEN.md: every ticket that isn't resolved yet.

Looks in two places:
  1. every branch except main: logbook entries that branch adds or changes
  2. main itself: entries merged with status open / in-progress / blocked
and links each one to its entry file (on its branch) and its pull request.

Usage (from the repo root, after `git fetch origin`):
  python -I code/local/build_open.py                  write OPEN.md
  python -I code/local/build_open.py --prs prs.json   also show pull requests
     (prs.json = output of: gh pr list --state open --json number,headRefName,url,isDraft)

No third-party packages. Output only changes when the tickets change.
"""
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
_spec = importlib.util.spec_from_file_location("build_index", ROOT / "code/local/build_index.py")
bi = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(bi)

ENTRY_DIRS = [f"knowledge/{d}" for d in bi.FOLDERS]
SKIP = ("README.md", "GUIDELINE.md")


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True,
                          text=True, encoding="utf-8").stdout


def is_entry(path):
    name = path.rsplit("/", 1)[-1]
    return path.endswith(".md") and not name.startswith("_") and name not in SKIP


def remote_branches():
    out = git("for-each-ref", "--format=%(refname:short)", "refs/remotes/origin")
    names = [r.split("/", 1)[1] for r in out.split() if "/" in r]
    return sorted(b for b in names if b not in ("main", "HEAD"))


def entries_on_branch(branch):
    ref = f"origin/{branch}"
    changed = git("diff", "--name-only", "origin/main..." + ref, "--", *ENTRY_DIRS).split()
    found = []
    for path in changed:
        if not is_entry(path):
            continue
        text = git("show", f"{ref}:{path}")
        fields, err = bi.parse_frontmatter(text) if text else (None, "deleted")
        if err or not fields:
            continue
        fields.update(path=path, ref=branch,
                      updated=git("log", "-1", "--format=%cs", ref, "--", path).strip())
        found.append(fields)
    return found


def entries_on_main():
    entries, _ = bi.load_entries()
    rows = []
    for e in entries:
        if e["status"] in bi.OPEN:
            e.update(ref="main", updated=git("log", "-1", "--format=%cs", "--", e["path"]).strip())
            rows.append(e)
    return rows


def load_prs(argv):
    if "--prs" not in argv:
        return None
    path = argv[argv.index("--prs") + 1]
    try:
        return {p["headRefName"]: p for p in json.loads(Path(path).read_text(encoding="utf-8"))}
    except (OSError, ValueError, KeyError):
        return None


def repo_url(*parts):
    return f"https://github.com/{bi.REPO}/" + "/".join(parts)


def ticket_cell(e, prs):
    if e["ref"] == "main":
        return "merged, still open"
    if prs is None:
        return f"[pull requests]({repo_url('pulls')})"
    pr = prs.get(e["ref"])
    if pr:
        state = "draft" if pr.get("isDraft") else "ready for review"
        return f"[PR #{pr['number']}]({pr['url']}) ({state})"
    return f"no PR yet - [open one]({repo_url('compare', 'main...' + e['ref'])}?expand=1)"


def build(rows, prs):
    rows.sort(key=lambda e: e["title"].lower())
    rows.sort(key=lambda e: e.get("updated") or "", reverse=True)
    blocked = sum(1 for e in rows if e["status"] == "blocked")
    out = [
        "# Open tickets",
        "",
        "<!-- GENERATED by code/local/build_open.py - do not edit by hand. -->",
        "",
        "Everything I've started and haven't resolved yet. Rebuilt automatically whenever I",
        "push to a ticket branch or open, close or merge a pull request.",
        "",
        f"**{bi.plural(len(rows), 'open ticket')}** · {blocked} blocked · "
        "resolved work is in the [logbook](LOGBOOK.md)",
        "",
        "Pick one up: `git switch <branch> && git pull`, then "
        "`bash code/local/worklog.sh \"what I did\"`.",
        "",
    ]
    if not rows:
        out.append("_Nothing open - nice._")
    else:
        out += ["| Status | Ticket | Type | Tech | Opened | Last update | Branch | Pull request |",
                "|---|---|---|---|---|---|---|---|"]
        for e in rows:
            link = repo_url("blob", e["ref"], e["path"])
            out.append("| " + " | ".join([
                f"**{e['status']}**",
                f"[{bi.cell(e['title'])}]({link})",
                bi.TYPE_NAME.get(e.get("type", ""), e.get("type", "-")),
                bi.tech_text(e) if isinstance(e.get("tech"), list) else "-",
                e.get("opened") or e.get("date") or "-",
                e.get("updated") or "-",
                f"[`{bi.cell(e['ref'])}`]({repo_url('tree', e['ref'])})",
                ticket_cell(e, prs),
            ]) + " |")
    return "\n".join(out).rstrip() + "\n"


def main(argv):
    prs = load_prs(argv)
    rows = entries_on_main()
    on_main = {e["path"] for e in rows}
    for branch in remote_branches():
        for e in entries_on_branch(branch):
            if e.get("status") in bi.OPEN:
                rows = [r for r in rows if r["path"] != e["path"]] if e["path"] in on_main else rows
                rows.append(e)
    bi.write(ROOT / "OPEN.md", build(rows, prs))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
